// Build knowledge/gen-quality.json from the distilled style library in
// ~/workspace/sw-prep/gen-quality/ (STYLE-BIBLE exemplars + hooks cards).
//
// The server loads the JSON once at startup (server/gemini.js,
// loadGenQuality) and injects, per chapter: ONE exemplar passage for the
// story's pinned genre template as a style anchor, plus 3–5 hook/craft
// cards drawn deterministically — the STYLE-BIBLE §10 quota discipline.
// The markdown in sw-prep stays the editorial source; re-run this script
// after editing it:
//
//   node scripts/build-gen-quality.mjs [sw-prep-gen-quality-dir]
//
// Exemplar → writing-template mapping: direct by genre family; templates
// without their own passage fall back to the nearest family's (campus
// writes like 都市, lishi like 古言, wuxianliu like 规则怪谈, zhihu-short
// like 悬疑, er-ren like 玄幻). The fallback is data, stated here once —
// the server never guesses.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const sourceDir = process.argv[2] || join(process.env.HOME, 'workspace/sw-prep/gen-quality')
const outPath = join(process.cwd(), 'knowledge/gen-quality.json')

const EXEMPLAR_FILES = {
  xuanhuan: '01-xuanhuan.md',
  xiuxian: '02-xiuxian.md',
  gaowu: '03-gaowu.md',
  dushi: '04-dushi.md',
  guizetanguai: '05-guizetanguai.md',
  kongbu: '06-kongbu.md',
  xuanyi: '07-xuanyi.md',
  xianyan: '08-xianyan.md',
  guyan: '09-guyan.md',
  kehuan: '10-kehuan.md',
}

// knowledge/genres.json template id -> exemplar key (direct, then the
// documented nearest-family fallbacks).
const TEMPLATE_EXEMPLARS = {
  xuanhuan: 'xuanhuan',
  xianxia: 'xiuxian',
  gaowu: 'gaowu',
  urban: 'dushi',
  'guize-guatan': 'guizetanguai',
  horror: 'kongbu',
  'suspense-supernatural': 'xuanyi',
  'romance-modern': 'xianyan',
  'romance-ancient': 'guyan',
  scifi: 'kehuan',
  campus: 'dushi',
  lishi: 'guyan',
  wuxianliu: 'guizetanguai',
  'zhihu-short': 'xuanyi',
  'er-ren': 'xuanhuan',
}

// The STYLE-BIBLE §5 four chapter-end hook types, and which H-cards
// perform each. The draw rotates the TYPE by chapter so one type never
// runs more than two chapters in a row (the rotation gives at most one).
const HOOK_TYPES = ['危机型', '反转型', '新人物型', '未完成动作型']
const HOOK_TYPE_OF_CARD = {
  'H-01': '危机型', 'H-06': '危机型', 'H-08': '危机型', 'H-11': '危机型', 'H-12': '危机型',
  'H-02': '反转型', 'H-10': '反转型',
  'H-03': '新人物型', 'H-05': '新人物型', 'H-09': '新人物型',
  'H-04': '未完成动作型', 'H-07': '未完成动作型',
}
const KIND_OF_PREFIX = { H: 'hook', F: 'face', P: 'reveal', T: 'horror', L: 'romance' }
// Which craft pools flavour a template's non-hook cards.爽文向 templates
// draw face-slap payoffs and hidden-strength reveals; horror/规则 draw
// horror closers; romance draws 心动 cards; the rest draw face cards
// (evidence-driven payoffs travel across genres).
const TEMPLATE_CARD_POOLS = {
  xuanhuan: ['face', 'reveal'],
  xianxia: ['face', 'reveal'],
  gaowu: ['face', 'reveal'],
  urban: ['face', 'reveal'],
  campus: ['face'],
  wuxianliu: ['face', 'reveal'],
  'er-ren': ['face', 'reveal'],
  horror: ['horror'],
  'guize-guatan': ['horror'],
  'romance-modern': ['romance'],
  'romance-ancient': ['romance'],
  'suspense-supernatural': ['face'],
  'zhihu-short': ['face'],
  scifi: ['face'],
  lishi: ['face'],
}

function exemplarText(file) {
  const raw = readFileSync(join(sourceDir, 'exemplars', file), 'utf8')
  const lines = raw.split('\n')
  const body = []
  for (const line of lines.slice(1)) {
    if (line.trim() === '---') break
    body.push(line)
  }
  return body.join('\n').trim()
}

function parseCards() {
  const raw = readFileSync(join(sourceDir, 'hooks.md'), 'utf8')
  const cards = []
  const blocks = raw.split(/\n\*\*([HFPTL]-\d+)\s+([^*]+)\*\*\n公式：([^\n]+)/)
  // split with captures: [pre, id, name, formula, rest, id, name, formula, rest...]
  for (let i = 1; i + 3 < blocks.length + 1 && i < blocks.length; i += 4) {
    const id = blocks[i]
    if (!id) continue
    const card = {
      id,
      name: blocks[i + 1].trim(),
      kind: KIND_OF_PREFIX[id[0]],
      formula: blocks[i + 2].trim(),
    }
    if (card.kind === 'hook') card.hookType = HOOK_TYPE_OF_CARD[id]
    cards.push(card)
  }
  return cards
}

const exemplars = {}
for (const [key, file] of Object.entries(EXEMPLAR_FILES)) {
  const text = exemplarText(file)
  if (!text || text.length > 420) throw new Error(`exemplar ${key}: ${text.length} chars`)
  exemplars[key] = text
}
const cards = parseCards()
if (cards.length !== 40) throw new Error(`cards: ${cards.length}`)
for (const card of cards) {
  if (card.kind === 'hook' && !card.hookType) throw new Error(`hook card ${card.id} has no hook type`)
}

const payload = {
  version: 1,
  note: 'Generated by scripts/build-gen-quality.mjs from ~/workspace/sw-prep/gen-quality — edit there, then re-run.',
  exemplars,
  templateExemplars: TEMPLATE_EXEMPLARS,
  hookTypes: HOOK_TYPES,
  templateCardPools: TEMPLATE_CARD_POOLS,
  cards,
}
writeFileSync(outPath, `${JSON.stringify(payload, null, 2)}\n`)
console.log(`wrote ${outPath}: ${Object.keys(exemplars).length} exemplars, ${cards.length} cards`)
