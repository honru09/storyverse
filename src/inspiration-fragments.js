/** Draw count distinct fragments at random from the whole library. */
export function drawInspirationFragments(count = 4, random = Math.random) {
  const rest = [...INSPIRATION_FRAGMENTS]
  const drawn = []
  while (drawn.length < count && rest.length) {
    drawn.push(rest.splice(Math.floor(random() * rest.length), 1)[0])
  }
  return drawn
}
